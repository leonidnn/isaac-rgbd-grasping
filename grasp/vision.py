"""Глаза для baseline: по карте глубины с верхней камеры прикидываем, где объект и как его брать.
Без всякого обучения, тупо правилом. Isaac тут не нужен, только numpy, можно гонять локально на depth.npy.

    x, y, z, yaw = pose(depth)   # всё в метрах/радианах, в осях мира (база робота в нуле)
"""

import math

import numpy as np

# камера как в common.CAMERA_TOP: 640x480, фокус 18 мм, матрица 20.955 мм, висит на (0, 0.5, 1.2) и смотрит вниз.
# сюда переписал руками, потому что common без запущенного кита не импортится. baseline сверяет с настоящей камерой
W, H = 640, 480
FX = FY = W * 18.0 / 20.955  # вертикальную апертуру isaac сам считает по пропорции, так что пиксели квадратные (вроде)
CX, CY = W / 2, H / 2
CAM = (0.0, 0.5, 1.2)

# что считаем объектом: выше стола на 1 см и ниже 25 см (чтоб руку робота не цеплять), и только над куском стола,
# куда env кидает объекты, плюс запас. Ближе 0.29 по y не смотрим: там в домашней позе висит кисть робота (y 0.25-0.27,
# высота до 26 см), из-за неё первый раз центр уехал на 14 см. Длинные чипсы у ближнего края слегка обрежутся, ну и ладно
MIN_H, MAX_H = 0.01, 0.25
X_BOX, Y_BOX = (-0.3, 0.3), (0.29, 0.75)
MIN_PIX = 30  # меньше - значит ничего не нашли, шум

GRIP_DEPTH = 0.03  # как у оракула: пальцы залезают на 3 см ниже верха
MIN_Z = 0.015


def to_world(depth):
    """Каждый пиксель в точку мира. Камера смотрит строго вниз: x картинки = x мира, вниз по картинке = -y мира."""
    v, u = np.mgrid[0:depth.shape[0], 0:depth.shape[1]]
    x = CAM[0] + (u - CX) * depth / FX
    y = CAM[1] - (v - CY) * depth / FY
    z = CAM[2] - depth
    return x, y, z


def mask(depth):
    x, y, z = to_world(depth)
    m = (depth > 0) & (z > MIN_H) & (z < MAX_H)
    m &= (x > X_BOX[0]) & (x < X_BOX[1]) & (y > Y_BOX[0]) & (y < Y_BOX[1])
    return m, x, y, z


def pose(depth):
    """Вернёт (x, y, z, yaw) или None, если объекта не видно."""
    m, x, y, z = mask(depth)
    if m.sum() < MIN_PIX:
        return None
    px, py, pz = x[m], y[m], z[m]

    # центр - просто среднее по точкам. Видно только верх объекта, но для схвата сверху это и надо
    cx, cy = px.mean(), py.mean()
    # верх берём не самый максимум, а 95-й процентиль, а то один кривой пиксель на краю всё портит
    top = np.percentile(pz, 95)
    gz = max(top - GRIP_DEPTH, MIN_Z)

    # PCA по точкам сверху: главная ось - вдоль чего объект длинный.
    # пальцы сжимаются вдоль yaw (выяснили в 4_env: yaw-offset 0 брал лежачий тетрапак по узким 6 см),
    # значит yaw надо направить по короткой оси, то есть по второй
    pts = np.stack([px - cx, py - cy])
    w, vec = np.linalg.eigh(np.cov(pts))  # собственные числа по возрастанию, нулевой - самая короткая ось
    short = vec[:, 0]
    yaw = math.atan2(short[1], short[0])
    return float(cx), float(cy), float(gz), float(yaw)


def pixel(x, y, depth_at):
    """Обратно из мира в пиксель, чтоб нарисовать крестик на картинке."""
    u = CX + (x - CAM[0]) * FX / depth_at
    v = CY - (y - CAM[1]) * FY / depth_at
    return u, v
